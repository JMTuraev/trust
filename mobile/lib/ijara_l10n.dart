const Map<String, Map<String, String>> kIjaraLangs = {
  'uz': _ijUz, 'ru': _ijRu, 'en': _ijEn, 'es': _ijEs, 'fr': _ijFr, 'zh': _ijZh,
};

/// Joriy til Ijara lug'ati (fallback: en).
Map<String, String> ijMap([String? lang]) =>
    kIjaraLangs[lang ?? (store.S['lang'] as String? ?? 'uz')] ?? _ijEn;

/// Kalitni oling va {token}'larni almashtiring. ij('overdueN', {'n': '2'}).
String ij(String key, [Map<String, String>? vars]) {
  var s = ijMap()[key] ?? _ijEn[key] ?? key;
  if (vars != null) vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Oy nomi (1..12).
String ijMonth(int m) => ij('mon${m.clamp(1, 12)}');

/// Hisob turi yorlig'i: 'ijara' | 'kommunal' | 'boshqa'.
String ijKind(String kind) => switch (kind) {
      'ijara' => ij('kindIjara'),
      'kommunal' => ij('kindKommunal'),
      _ => ij('kindBoshqa'),
    };

