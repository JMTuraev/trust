const Map<String, Map<String, String>> kToyLangs = {
  'uz': _tyUz, 'ru': _tyRu, 'en': _tyEn, 'es': _tyEs, 'fr': _tyFr, 'zh': _tyZh,
};

/// Joriy til To'yxona lug'ati (fallback: en).
Map<String, String> tyMap([String? lang]) =>
    kToyLangs[lang ?? (store.S['lang'] as String? ?? 'uz')] ?? _tyEn;

/// Kalitni oling va {token}'larni almashtiring. ty('guestsN', {'n': '300'}).
String ty(String key, [Map<String, String>? vars]) {
  var s = tyMap()[key] ?? _tyEn[key] ?? key;
  if (vars != null) vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

/// Oy nomi (1..12).
String tyMonth(int m) => ty('mon${m.clamp(1, 12)}');

/// Hafta kuni qisqartmasi (1 = dushanba .. 7 = yakshanba).
String tyWeekday(int w) => ty('wd${w.clamp(1, 7)}');

/// Slot yorlig'i: 'nahor' | 'tushlik' | 'kechki'.
String tySlot(String slot) => switch (slot) {
      'nahor' => ty('slotNahor'),
      'tushlik' => ty('slotTushlik'),
      _ => ty('slotKechki'),
    };

/// Holat yorlig'i: 'band' | 'tasdiq' | 'yakun' | 'bekor'.
String tyStatus(String status) => switch (status) {
      'tasdiq' => ty('stTasdiq'),
      'yakun' => ty('stYakun'),
      'bekor' => ty('stBekor'),
      _ => ty('stBand'),
    };

